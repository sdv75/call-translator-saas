'use strict';
const assert=require('node:assert/strict');
require('./language-library.js');
const setup=require('./voice-setup.js');
const uk={id:'uk',version:'1',language:'uk'},en={id:'en',version:'1',language:'en'},ru={id:'ru',version:'1',language:'ru'};
assert.equal(setup.languages([uk,en]).find(item=>item.code==='ru').available,false);
assert.equal(setup.pair([uk,en],'ru','uk'),false);
assert.deepEqual(setup.forDirection([uk,en],'ru','uk','outgoing'),[]);
const voices=[uk,en,ru];
assert.equal(setup.languages(voices).find(item=>item.code==='ru').available,true);
assert.deepEqual(setup.forDirection(voices,'ru','uk','incoming'),[ru]);
assert.deepEqual(setup.forDirection(voices,'ru','uk','outgoing'),[uk]);
assert.equal(setup.pair(voices,'ru','ru'),false);
assert.equal(setup.ready(voices,{voices:[uk,ru],selected:{incoming:'ru',outgoing:'uk'}},'ru','uk'),true);
assert.equal(setup.ready(voices,{voices:[uk,en],selected:{incoming:'ru',outgoing:'uk'}},'ru','uk'),false);
assert.equal(setup.ready(voices,{voices:[uk,ru],selected:{incoming:'uk',outgoing:'ru'}},'ru','uk'),false);
assert.equal(setup.pair([uk,{...ru,compatible:false}],'ru','uk'),false);
const female={...en,gender:'female'},male={...en,id:'en-male',gender:'male'};
assert.deepEqual(setup.forDirection([ru,female,male],'ru','en','outgoing','male'),[male]);
assert.equal(setup.ready([ru,female,male],{voices:[ru,female],selected:{incoming:ru.id,outgoing:female.id}},'ru','en',{outgoing:'male'}),false);
const variants=setup.variants([female,male,{...ru,gender:'male'}]);
assert.equal(new Set(variants.map(item=>item.language)).size,2);
assert.equal(variants.some(item=>item.value==='ru:female'),false);
assert.equal(variants.find(item=>item.value==='en:male').available,true);
assert.equal(setup.restoreVariant([female,male],'en','all',female.id),'en:female');
assert.equal(setup.restoreVariant([female,male],'en','all',null),'');
assert.equal(setup.restoreVariant([female,male],'en','male',female.id),'en:male');
assert.deepEqual(setup.variants([{...male,language:'cy'}]),[]);
assert.deepEqual(setup.variants([{...male,compatible:false}]),[]);
const fs=require('node:fs');
const envelope=JSON.parse(fs.readFileSync('catalog/voices.all.signed.json','utf8'));
const published=JSON.parse(Buffer.from(envelope.payload,'base64').toString('utf8'));
const publishedVariants=setup.variants(published.voices);
assert.equal(new Set(publishedVariants.map(item=>item.language)).size,29);
assert.equal(publishedVariants.length,41);
assert(publishedVariants.every(item=>item.available));
console.log('Voice setup: catalog availability, selected-pair filtering, direction mapping and saved-voice readiness passed');
